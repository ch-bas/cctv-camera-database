#!/usr/bin/env node
// Regenerates tools/qa-validator.js from schema/camera.schema.json.
// Run after any schema change:  node tools/build-qa-validator.js
// Requires esbuild (npm i --no-save esbuild) besides the repo devDeps.

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const Ajv = require('ajv');
const standaloneCode = require('ajv/dist/standalone').default;
const addFormats = require('ajv-formats');

const root = path.join(__dirname, '..');
const schemaPath = path.join(root, 'schema', 'camera.schema.json');
const outPath = path.join(__dirname, 'qa-validator.js');
const tmpPath = path.join(__dirname, '.qa-validator.tmp.cjs');

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

const ajv = new Ajv({ code: { source: true }, allErrors: true, strict: false });
addFormats(ajv);
const validate = ajv.compile(schema);
fs.writeFileSync(tmpPath, standaloneCode(ajv, validate));

// Bundle the CJS standalone output (it requires ajv runtime helpers) into
// a single IIFE exposing window.validateCamera.
// try/finally so a failed esbuild run doesn't leave the temp .cjs behind.
try {
  execSync(
    `npx esbuild ${JSON.stringify(tmpPath)} --bundle --minify --format=iife --global-name=__qaValidate --outfile=${JSON.stringify(outPath)}`,
    { cwd: root, stdio: 'inherit' }
  );
} finally {
  if (fs.existsSync(tmpPath)) fs.unlinkSync(tmpPath);
}

// Append the browser-facing wrapper + provenance stamp.
const stamp = {
  schema: 'schema/camera.schema.json',
  schema_title: schema.title ?? null,
  generated: new Date().toISOString().slice(0, 10),
};
fs.appendFileSync(outPath, `
// Generated by tools/build-qa-validator.js — do not edit by hand.
// Regenerate after schema changes: node tools/build-qa-validator.js
window.validateCamera = __qaValidate.default ?? __qaValidate;
window.QA_VALIDATOR_INFO = ${JSON.stringify(stamp)};
`);

console.log('✓ wrote', path.relative(root, outPath), stamp);
